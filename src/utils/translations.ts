/**
 * Helper to safely retrieve a localized string with optional fallback
 */
export function getTranslation(language: Language, key: string, fallback?: string): string {
  const langDict = translations[language] || translations.fa;
  if (langDict && langDict[key]) {
    return langDict[key];
  }
  const fallbackDict = translations.fa;
  if (fallbackDict && fallbackDict[key]) {
    return fallbackDict[key];
  }
  return fallback || key;
}

/**
 * Returns true if language direction is Right-to-Left
 */
export function isRtlLanguage(language: Language): boolean {
  return language === 'fa' || language === 'ar';
}
