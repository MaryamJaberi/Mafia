export interface SearchIndexItem {
  scenario: string;
  scenarioName: string;
  roleA: string;
  roleB: string | null;
  text: string;
  isDiag: boolean;
  a?: string;
  b?: string;
  genRef?: GeneralRole;
  otherRef?: OtherScenario;
}

export function buildSearchIndex(): SearchIndexItem[] {
  const idx: SearchIndexItem[] = [];
  MATRIX_SCENARIOS.forEach(s => {
    s.roles.forEach(r => {
      const text = s.cellMap?.[pair(r.id, r.id)] || '';
      idx.push({
        scenario: s.id,
        scenarioName: s.name,
        roleA: r.n,
        roleB: null,
        text,
        isDiag: true,
        a: r.id,
        b: r.id
      });
    });
    s.cells.forEach(c => {
      if (c.a === c.b) return;
      if (!c.t || !c.t.trim()) return;
      const ra = s.roles.find(r => r.id === c.a);
      const rb = s.roles.find(r => r.id === c.b);
      idx.push({
        scenario: s.id,
        scenarioName: s.name,
        roleA: ra?.n || c.a,
        roleB: rb?.n || c.b,
        text: c.t,
        isDiag: false,
        a: c.a,
        b: c.b
      });
    });
  });
  GENERAL_ROLES.forEach(r => {
    idx.push({
      scenario: 'general',
      scenarioName: 'نقش‌های عمومی',
      roleA: r.n,
      roleB: null,
      text: `${r.d} ${r.ex}`,
      isDiag: true,
      genRef: r
    });
  });
  OTHER_SCENARIOS.forEach(r => {
    idx.push({
      scenario: 'other',
      scenarioName: 'سایر سناریوهای گرگینه',
      roleA: r.n,
      roleB: null,
      text: `${r.d} ${r.ex}`,
      isDiag: true,
      otherRef: r
    });
  });
  return idx;
}

const CUSTOM_SCENARIOS_STORAGE_KEY = 'mafia_custom_matrix_scenarios_v1';

export function getCustomMatrixScenarios(): MatrixScenario[] {
  try {
    const raw = localStorage.getItem(CUSTOM_SCENARIOS_STORAGE_KEY);
    if (!raw) return [];
    const list: MatrixScenario[] = JSON.parse(raw);
    return list.map(s => {
      const map: Record<string, string> = {};
      s.cells.forEach(c => {
        map[pair(c.a, c.b)] = c.t;
      });
      return { ...s, cellMap: map };
    });
  } catch (err) {
    console.error('Failed to load custom matrix scenarios:', err);
    return [];
  }
}

export function saveCustomMatrixScenario(scenario: MatrixScenario): void {
  try {
    const existing = getCustomMatrixScenarios();
    const map: Record<string, string> = {};
    scenario.cells.forEach(c => {
      map[pair(c.a, c.b)] = c.t;
    });
    const prepared = { ...scenario, cellMap: map };
    const filtered = existing.filter(s => s.id !== scenario.id);
    filtered.unshift(prepared);
    localStorage.setItem(CUSTOM_SCENARIOS_STORAGE_KEY, JSON.stringify(filtered));
  } catch (err) {
    console.error('Failed to save custom matrix scenario:', err);
  }
}

export function deleteCustomMatrixScenario(id: string): void {
  try {
    const existing = getCustomMatrixScenarios();
    const filtered = existing.filter(s => s.id !== id);
    localStorage.setItem(CUSTOM_SCENARIOS_STORAGE_KEY, JSON.stringify(filtered));
  } catch (err) {
    console.error('Failed to delete custom matrix scenario:', err);
  }
}

export function getAllMatrixScenarios(): MatrixScenario[] {
  const customs = getCustomMatrixScenarios();
  return [...customs, ...MATRIX_SCENARIOS];
}

